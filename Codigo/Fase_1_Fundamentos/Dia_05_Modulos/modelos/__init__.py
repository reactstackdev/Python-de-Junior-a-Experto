# __init__.py dentro de cada carpeta que quieras tratar como paquete. Está vacío, pero indica explícitamente "esta carpeta es un módulo".

# Por lo tanto un __init__.py indica que son paquetes, y dentro de cada paquete puedes importar los módulos que quieras. 
# De esta forma, al importar el paquete, también se importan los módulos que hay dentro de él.